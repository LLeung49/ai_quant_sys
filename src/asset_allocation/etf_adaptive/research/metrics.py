"""Performance metrics, baselines, and mode attribution for research output.

These helpers consume the cost-net NAV series produced by the backtest
engine and the ``Trade`` records generated by execution. They never reach
back into the engine or the provider; the only state they observe is what
the engine has already serialised into the metrics inputs.
"""

from __future__ import annotations

from dataclasses import dataclass
from datetime import date
from decimal import Decimal
from math import sqrt
from typing import Iterable, Literal, Sequence


SESSIONS_PER_YEAR: int = 252
WORST_WINDOW_SESSIONS: int = 126
CVAR_ALPHA: float = 0.05


ModeName = Literal["grid", "trend", "transition", "cost"]


@dataclass(frozen=True)
class Trade:
    """Minimal record used by ``calculate_performance``.

    ``commission`` and ``slippage_cost`` are Decimal to mirror the engine.
    ``is_unfilled`` is true when the engine produced no fill for the intent.
    ``minimum_commission_applied`` is true when the broker minimum dominated
    the percentage commission.
    """

    signal_date: date
    fill_date: date
    side: str
    shares: int
    raw_price: float
    commission: Decimal
    slippage_cost: Decimal
    minimum_commission_applied: bool
    is_unfilled: bool


@dataclass(frozen=True)
class PerformanceMetrics:
    annual_return: float
    annual_volatility: float
    sharpe: float
    sortino: float
    calmar: float
    worst_126_session_return: float
    cvar5: float
    win_rate: float
    payoff_ratio: float
    profit_factor: float
    turnover: float
    minimum_commission_share: float
    unfilled_share: float
    slippage_degradation: float
    max_drawdown: float
    recovery_sessions: int
    total_cost: float


@dataclass(frozen=True)
class AttributionEvent:
    """Tagged P&L or cost contribution to a single research event."""

    mode: ModeName
    amount: float


@dataclass(frozen=True)
class ModeAttribution:
    grid_pnl: float
    trend_pnl: float
    transition_pnl: float
    costs: float

    @property
    def net_total(self) -> float:
        return self.grid_pnl + self.trend_pnl + self.transition_pnl - self.costs


def _require_finite_sequence(values: Sequence[float], name: str) -> None:
    for index, value in enumerate(values):
        if not isinstance(value, (int, float)) or value != value or value in (float("inf"), float("-inf")):
            raise ValueError(f"{name}[{index}] must be a finite number, got {value!r}")


def max_drawdown(nav: Sequence[float]) -> float:
    """Return the most negative percentage drawdown of ``nav``."""

    if not nav:
        raise ValueError("nav must not be empty")
    _require_finite_sequence(nav, "nav")
    peak = nav[0]
    worst = 0.0
    for value in nav:
        if value <= 0:
            raise ValueError("nav values must be positive")
        if value > peak:
            peak = value
        drawdown = value / peak - 1.0
        if drawdown < worst:
            worst = drawdown
    return float(worst)


def recovery_sessions(nav: Sequence[float]) -> int:
    """Return the index of the first session that recovers above the previous peak.

    If the NAV never recovers, return ``len(nav)``.
    """

    if not nav:
        raise ValueError("nav must not be empty")
    _require_finite_sequence(nav, "nav")
    peak = nav[0]
    peak_index = 0
    for index, value in enumerate(nav):
        if value > peak:
            if peak_index == 0:
                return index
            peak = value
            peak_index = index
    return len(nav)


def session_returns(nav: Sequence[float]) -> tuple[float, ...]:
    """Return the simple return between consecutive NAV observations."""

    if len(nav) < 2:
        raise ValueError("session_returns requires at least two nav observations")
    _require_finite_sequence(nav, "nav")
    returns = []
    for previous, current in zip(nav, nav[1:]):
        if previous <= 0:
            raise ValueError("nav values must be positive")
        returns.append(current / previous - 1.0)
    return tuple(returns)


def _mean(values: Sequence[float]) -> float:
    return sum(values) / len(values) if values else 0.0


def _population_std(values: Sequence[float]) -> float:
    if not values:
        return 0.0
    mean = _mean(values)
    return sqrt(sum((value - mean) ** 2 for value in values) / len(values))


def _downside_std(returns: Sequence[float]) -> float:
    negatives = [value for value in returns if value < 0.0]
    if not negatives:
        return 0.0
    return _population_std(negatives)


def _worst_window_return(returns: Sequence[float], window: int) -> float:
    """Return the most negative compound return over a sliding ``window``.

    When the available data is shorter than ``window`` the metric falls back
    to the longest available window so short research runs still report a
    meaningful value rather than 0.0.
    """

    if not returns or window <= 0:
        return 0.0
    worst = float("inf")
    cumulative = 1.0
    buffer: list[float] = []
    for value in returns:
        buffer.append(value)
        cumulative *= (1.0 + value)
        if len(buffer) > window:
            oldest = buffer.pop(0)
            cumulative = cumulative / (1.0 + oldest) if (1.0 + oldest) != 0 else 0.0
        is_full_window = len(buffer) >= window
        is_short_terminal = len(buffer) < window and len(returns) == len(buffer)
        if is_full_window or is_short_terminal:
            worst = min(worst, cumulative - 1.0)
    if worst == float("inf"):
        return 0.0
    return float(worst)


def _cvar(returns: Sequence[float], alpha: float) -> float:
    if not returns or alpha <= 0.0:
        return 0.0
    sorted_returns = sorted(returns)
    cutoff_index = max(1, int(len(sorted_returns) * alpha))
    tail = sorted_returns[:cutoff_index]
    return float(_mean(tail))


def calculate_performance(
    nav: Sequence[float], trades: Sequence[Trade],
) -> PerformanceMetrics:
    """Compute the full ``PerformanceMetrics`` snapshot for one research run."""

    if not nav:
        raise ValueError("nav must not be empty")
    _require_finite_sequence(nav, "nav")
    returns = session_returns(nav)
    drawdown = max_drawdown(nav)
    total_cost = float(sum((trade.commission + trade.slippage_cost) for trade in trades))
    commission_only = float(sum(trade.commission for trade in trades))
    slippage_only = float(sum(trade.slippage_cost for trade in trades))

    total_return = nav[-1] / nav[0] - 1.0 if nav[0] > 0 else 0.0
    sessions = max(len(nav) - 1, 1)
    annual_return = (1.0 + total_return) ** (SESSIONS_PER_YEAR / sessions) - 1.0 if total_return > -1.0 else -1.0
    annual_vol = _population_std(returns) * sqrt(SESSIONS_PER_YEAR)
    downside_vol = _downside_std(returns) * sqrt(SESSIONS_PER_YEAR)
    sharpe = annual_return / annual_vol if annual_vol > 0 else 0.0
    sortino = annual_return / downside_vol if downside_vol > 0 else 0.0
    calmar = annual_return / abs(drawdown) if drawdown < 0 else 0.0

    positives = [value for value in returns if value > 0.0]
    negatives = [value for value in returns if value < 0.0]
    win_rate = len(positives) / len(returns) if returns else 0.0
    payoff_ratio = (
        _mean(positives) / abs(_mean(negatives)) if positives and negatives else 0.0
    )
    profit_factor = (
        sum(positives) / abs(sum(negatives)) if positives and negatives else 0.0
    )

    minimum_commission_share = (
        sum(1 for trade in trades if trade.minimum_commission_applied) / len(trades)
        if trades else 0.0
    )
    unfilled_share = (
        sum(1 for trade in trades if trade.is_unfilled) / len(trades) if trades else 0.0
    )

    average_nav = _mean(nav)
    gross_traded_value = sum(
        (trade.raw_price or 0.0) * max(trade.shares, 0) for trade in trades
    )
    turnover = gross_traded_value / average_nav if average_nav > 0 else 0.0
    slippage_degradation = (
        slippage_only / commission_only if commission_only > 0 else 0.0
    )

    return PerformanceMetrics(
        annual_return=float(annual_return),
        annual_volatility=float(annual_vol),
        sharpe=float(sharpe),
        sortino=float(sortino),
        calmar=float(calmar),
        worst_126_session_return=_worst_window_return(returns, WORST_WINDOW_SESSIONS),
        cvar5=_cvar(returns, CVAR_ALPHA),
        win_rate=float(win_rate),
        payoff_ratio=float(payoff_ratio),
        profit_factor=float(profit_factor),
        turnover=float(turnover),
        minimum_commission_share=float(minimum_commission_share),
        unfilled_share=float(unfilled_share),
        slippage_degradation=float(slippage_degradation),
        max_drawdown=float(drawdown),
        recovery_sessions=recovery_sessions(nav),
        total_cost=float(total_cost),
    )


_VALID_MODES: frozenset[str] = frozenset({"grid", "trend", "transition", "cost"})


def attribute_by_mode(events: Iterable[AttributionEvent]) -> ModeAttribution:
    """Aggregate ``AttributionEvent`` records into a ``ModeAttribution``."""

    grid_pnl = 0.0
    trend_pnl = 0.0
    transition_pnl = 0.0
    costs = 0.0
    for event in events:
        if event.mode not in _VALID_MODES:
            raise ValueError(f"unknown attribution mode: {event.mode!r}")
        if event.mode == "grid":
            grid_pnl += event.amount
        elif event.mode == "trend":
            trend_pnl += event.amount
        elif event.mode == "transition":
            transition_pnl += event.amount
        else:
            costs += event.amount
    return ModeAttribution(
        grid_pnl=grid_pnl,
        trend_pnl=trend_pnl,
        transition_pnl=transition_pnl,
        costs=costs,
    )
